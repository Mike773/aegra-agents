"""Как агент работает инструментами — операционная часть промпта.

Инструментов немного и они широкие: один вызов должен закрывать вопрос
целиком, потому что каждый вызов — отдельный обмен с моделью.
"""
from __future__ import annotations

TOOLS_GUIDE_TEMPLATE = """КАК РАБОТАТЬ С ДАННЫМИ И ИНСТРУМЕНТАМИ
Данные о показателях доступны тебе ТОЛЬКО через инструменты — по памяти чисел не приводи.

- Начинай с карты отклонений: она уже посчитана по данным и отранжирована по
  важности. `list_deviations` показывает её целиком (в промпте — только верхушка).
- `metric_card` — всё об одном показателе за один вызов: описание, значения по
  периодам, план и вердикты, разрезы, состав (дети с весами влияния), место
  среди коллег. Это первый инструмент, когда нужно разобраться в показателе.
- `query_sql` — свободный SELECT по схеме ниже, когда нужен срез, которого нет в
  карточке: ранжирование, фильтр, сравнение нескольких показателей, история.
  Обязательно передавай `purpose` — короткую цель запроса по-русски.
- `peer_context` — сравнение с коллегами по группам от узкой к широкой.
- `search_wiki` — методика, нормативы, расшифровка аббревиатур. Это справка для
  интерпретации, а НЕ источник чисел.
- `note_deviation` — если нашёл то, чего нет в карте: отметь, и это переживёт
  следующие вопросы руководителя.

Правила работы:
- Один вызов инструмента за шаг. Не повторяй вызов с теми же аргументами: если
  данных не хватило, меняй параметры или инструмент.
- Бюджет вызовов на этот ответ — {budget}. Уложись и переходи к ответу; лучше
  меньше вызовов и уверенный вывод, чем перебор всех показателей.
- Последние значения РАЗНЫХ показателей могут быть на РАЗНЫЕ даты: у дочерних
  показателей данные часто приходят позже. Бери последнее значение серии
  (`is_last_of_series` = 1, представление `v_fact_latest`) и сверяй колонку
  `date`. Не отбрасывай показатель из-за того, что его дата старше соседней, и
  не считай, что у всех дата общая.
- Вердикты (`plan_status`, `pop_status`, `trend_status`, `peer_status`) уже
  учитывают направление показателя — переноси их, не выводи оценку заново.
- Когда данных достаточно, ответь текстом БЕЗ вызова инструментов: этот текст и
  увидит руководитель."""


def tools_guide_block(budget: int) -> str:
    return TOOLS_GUIDE_TEMPLATE.format(budget=budget)


__all__ = ["TOOLS_GUIDE_TEMPLATE", "tools_guide_block"]
