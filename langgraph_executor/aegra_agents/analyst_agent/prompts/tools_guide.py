"""Как агент работает инструментами — операционная часть промпта.

Инструментов немного и они широкие: один вызов должен закрывать вопрос
целиком, потому что каждый вызов — отдельный обмен с моделью.
"""
from __future__ import annotations

TOOLS_GUIDE_TEMPLATE = """КАК РАБОТАТЬ С ДАННЫМИ И ИНСТРУМЕНТАМИ
Данные о показателях доступны тебе ТОЛЬКО через инструменты — по памяти чисел не
приводи. Что делает каждый инструмент и какие у него аргументы, написано в его
описании.

- Разбор показателей начинай с `deviation_map`. По ней составляй список
  отклонений по алгоритму из первого запроса руководителя: что считать
  отклонением и как выбирать главное. Отдельный показатель — `metric_card`{sql_hint}.{stars_hint}
- Один вызов инструмента за шаг. Не повторяй вызов с теми же аргументами: если
  данных не хватило, меняй параметры или инструмент.
- Бюджет вызовов на этот ответ — {budget}. Уложись и переходи к ответу; лучше
  меньше вызовов и уверенный вывод, чем перебор всех показателей.
- Последние значения РАЗНЫХ показателей могут быть на РАЗНЫЕ даты: у дочерних
  показателей данные часто приходят позже. Бери последнее значение серии
  (`is_last_of_series` = 1, представление `v_fact_latest`) и сверяй колонку
  `date`. Не отбрасывай показатель из-за того, что его дата старше соседней, и
  не считай, что у всех дата общая.
- Вердикты (`plan_status`, `pop_status`, `trend_status`, `peer_status`) уже
  учитывают направление показателя — переноси их, не выводи оценку заново.
- Разрезов у показателя бывают СОТНИ, в описании показателя дано только их
  число. Не перечисляй разрезы и не запрашивай их списком.
- Если у показателя помечено «своего итога нет», у него нет общего значения:
  не складывай разрезы в итог и не называй сумму фактом. Говори о разрезах и
  прямо отмечай, что итога по показателю в данных нет.
- Когда данных достаточно, ответь текстом БЕЗ вызова инструментов: этот текст и
  увидит руководитель."""


_SQL_HINT = (
    "; SQL — когда нужен срез, которого там нет (схема базы и примеры "
    "запросов — в описании `query_sql`)"
)


# Только при звёздах в данных: карта тогда — показатели неполученных звёзд,
# а модель всё равно выносила в фокус верхний показатель вне звёзд.
_STARS_HINT = (
    "\n- У сотрудника есть звёзды: тогда `deviation_map` даёт только показатели"
    "\n  НЕполученных звёзд, и главный фокус ответа выбирай среди них. Показатели"
    "\n  вне звёзд в главный фокус не выноси, если руководитель прямо не спросил о них."
)


def tools_guide_block(budget: int, *, has_sql: bool = True, has_stars: bool = False) -> str:
    return TOOLS_GUIDE_TEMPLATE.format(
        budget=budget,
        sql_hint=_SQL_HINT if has_sql else "",
        stars_hint=_STARS_HINT if has_stars else "",
    )


__all__ = ["TOOLS_GUIDE_TEMPLATE", "tools_guide_block"]
