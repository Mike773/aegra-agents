"""Главный вывод для сервиса инсайтов — из ответа агента.

Фокус ответа выбирает модель, по алгоритму из первого запроса руководителя,
поэтому и главный вывод берётся из её ответа, а не из правил кода. Модель
только называет вывод: тип, показатель и суть. Идентификатор показателя,
факт и план код подставляет из данных.
"""
from __future__ import annotations

from typing import Any

MAIN_INSIGHT_TOOL = "save_main_insight"

MAIN_INSIGHT_TOOL_DESCRIPTION = "Сохранить главный вывод из разбора аналитика."

MAIN_INSIGHT_PROMPT = (
    "Тебе дан разбор показателей сотрудника, который аналитик написал для "
    "руководителя. Выдели из него ОДИН главный вывод — тот, что аналитик сам "
    "назвал главным фокусом.\n\n"
    "Тип вывода (поле type):\n"
    "- main_problem — главный фокус разбора — отклонение в худшую сторону, зона "
    "развития;\n"
    "- achievement — главный фокус — достижение: план выполнен или перевыполнен, "
    "позитивная динамика;\n"
    "- norm — существенных отклонений нет, показатели в норме.\n\n"
    "Правила:\n"
    "1. Бери только то, что написано в разборе: не добавляй своих выводов и чисел.\n"
    "2. metric — название показателя, который аналитик назвал главным фокусом "
    "(обычно он стоит в разделе «Главный фокус»), ровно так, как оно написано в "
    "разборе. Не подменяй его причиной: если аналитик объясняет просадку "
    "фокусного показателя через влияющий показатель, metric — всё равно сам "
    "фокусный. Если вывод про разрез показателя, указывай сам показатель. Для "
    "norm без конкретного показателя оставь пустую строку.\n"
    "3. text — суть вывода в одном-двух предложениях, с числами из разбора."
)

MAIN_INSIGHT_SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {
        "type": {
            "type": "string",
            "enum": ["main_problem", "achievement", "norm"],
            "description": "Тип главного вывода",
        },
        "metric": {
            "type": "string",
            "description": "Название показателя главного фокуса, как в разборе",
        },
        "text": {
            "type": "string",
            "description": "Суть вывода в одном-двух предложениях, с числами",
        },
    },
    "required": ["type", "metric", "text"],
}


